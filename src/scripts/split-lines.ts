/* ------------------------------------------------------------
   Разбивка заголовков на строки-маски.

   Заголовок секции должен выезжать из-под края построчно — для
   этого каждой строке нужна своя маска (.rise). Писать это руками
   значило бы завести по паре вложенных span на каждый из десяти
   заголовков и следить, чтобы вёрстка не разъехалась при правке
   текста. Здесь то же самое делается один раз и автоматически:
   исходная разметка остаётся чистой — <h2 class="head">строка<br>строка</h2>.

   Делим только по уже существующим <br>: это ровно те переносы,
   которые автор задал руками, поэтому смысл и озвучивание
   скринридером не меняются — текст остаётся внутри того же
   заголовка. Без JS заголовок просто не разбит и виден целиком.
   ------------------------------------------------------------ */
function initSplitLines() {
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;

  const heads = document.querySelectorAll<HTMLElement>('.head, [data-split]');

  heads.forEach((head) => {
    // уже размечено руками (обложка) — не трогаем
    if (head.querySelector('.rise')) return;

    const lines = head.innerHTML.split(/<br\s*\/?>/i);
    head.innerHTML = lines
      .map((line) => `<span class="rise"><span>${line.trim()}</span></span>`)
      .join('');
  });
}

initSplitLines();
